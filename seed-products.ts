async function main() {
  const db = await getDb();
  if (!db) throw new Error("DATABASE_URL is not configured");
  const existing = await listProducts();
  const existingNames = new Set(existing.map(product => product.name));
  const missing = catalog.filter(item => !existingNames.has(item.name));
  for (const item of missing) {
    await createProduct({
      ...item,
      slug: `${item.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      currency: "INR",
    });
  }
  const currentProducts = await listProducts();
  let seededVariants = 0;
  for (const [name, detailSeed] of Object.entries(detailCatalog)) {
    const product = currentProducts.find(candidate => candidate.name === name);
    if (!product) continue;
    await db.update(products).set({ specifications: detailSeed.specifications }).where(eq(products.id, product.id));
    const existingVariants = await db.select().from(productVariants).where(eq(productVariants.productId, product.id));
    const existingSkus = new Set(existingVariants.map(variant => variant.sku));
    for (const variant of detailSeed.variants) {
      if (existingSkus.has(variant.sku)) continue;
      await db.insert(productVariants).values({ productId: product.id, ...variant });
      seededVariants += 1;
    }
  }
  console.log(`${missing.length ? `Seeded ${missing.length} new YuvaCart products` : "Catalog is already up to date"}; added ${seededVariants} new variants.`);
  process.exit(0);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
